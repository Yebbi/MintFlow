"""
eval_pde/residuals/reaction_diffusion.py
==========================================
Reaction-diffusion (Fisher-KPP) building blocks for the ``rd1d`` dataset.

Ground-truth data (``datasets/data/RD_neumann_*.h5``) is generated by a
Strang-split solver (``datasets/generate_RD1d_data.py``) for::

    du/dt = nu * d2u/dx2 + rho * u * (1 - u)      (Neumann BCs: du/dx = gL, gR)

with ``rho = 0.01``, ``nu = 0.005`` (see HDF5 root attrs, disambiguated in
``eval_pde.config.PDEConfig`` as ``rd_rho`` / ``rd_nu``).

``mass_residual_rd_batched`` is the NumPy evaluation counterpart of the
differentiable global-balance identity in
``sampling.constraints.Residuals.mass_residual_rd``.
"""
from __future__ import annotations

import numpy as np


def mass_residual_rd_batched(u: np.ndarray, x: np.ndarray, t_grid: np.ndarray, rho: float, nu: float) -> np.ndarray:
    """Vectorized analogue of ``sampling.constraints.Residuals.mass_residual_rd``.

    Parameters
    ----------
    u      : ``(N, nx, nt)`` batch of samples.
    x      : ``(nx,)`` spatial grid (used only for ``dx = x[1]-x[0]``).
    t_grid : ``(nt,)`` time grid (need not be uniform).
    rho, nu : Reaction-rate / diffusion-coefficient constants.

    Returns
    -------
    ``(N, nt - 1)`` residual array — mirrors
    ``Residuals.mass_residual_rd(u_flat)[1:]`` used inside
    ``full_residual_rd`` (the trivial ``t=0`` entry is dropped).
    """
    u = np.asarray(u, dtype=np.float64)
    x = np.asarray(x, dtype=np.float64)
    t_grid = np.asarray(t_grid, dtype=np.float64)
    dx = float(x[1] - x[0])
    dt = np.diff(t_grid)                                    # (nt-1,)

    sol = np.transpose(u, (0, 2, 1))                         # (N, nt, nx)
    N = sol.shape[0]

    mass = sol.sum(axis=2) * dx                               # (N, nt)
    S = rho * (sol * (1.0 - sol)).sum(axis=2) * dx            # (N, nt)
    S_mid = 0.5 * (S[:, :-1] + S[:, 1:])                       # (N, nt-1)
    S_cum = np.concatenate(
        [np.zeros((N, 1)), np.cumsum(S_mid * dt[None, :], axis=1)], axis=1
    )                                                          # (N, nt)

    gL_t = -nu * (-25 * sol[:, :, 0] + 48 * sol[:, :, 1] - 36 * sol[:, :, 2]
                  + 16 * sol[:, :, 3] - 3 * sol[:, :, 4]) / (12 * dx)   # (N, nt)
    gR_t = -nu * (25 * sol[:, :, -1] - 48 * sol[:, :, -2] + 36 * sol[:, :, -3]
                  - 16 * sol[:, :, -4] + 3 * sol[:, :, -5]) / (12 * dx)  # (N, nt)
    F = gL_t - gR_t
    F_mid = 0.5 * (F[:, :-1] + F[:, 1:])
    F_cum = np.concatenate(
        [np.zeros((N, 1)), np.cumsum(F_mid * dt[None, :], axis=1)], axis=1
    )

    residual = mass - (mass[:, :1] + S_cum + F_cum)            # (N, nt)
    return residual[:, 1:]                                     # drop trivial t=0
